// ─── Queue Event Types ────────────────────────────────────────────────────────

/**
 * INTERACTION — slash command sent by a user in Discord.
 * AI rule: summarize/tag the command text.
 */
export interface InteractionQueueEvent {
  kind: "INTERACTION";
  interactionId: string;
  guildId: string | null;
  channelId: string | null;
  userId: string;
  username: string;
  commandName: string;
  commandOptions: DiscordCommandOption[];
  token: string;
  applicationId: string;
  receivedAt: string; // ISO timestamp
}

/**
 * BOT_MESSAGE — a normal message the bot wants to send to a channel.
 * AI rule: classify intent, format/enrich the message content.
 * No interaction token. No Slack mirror by default.
 */
export interface BotMessageQueueEvent {
  kind: "BOT_MESSAGE";
  messageId: string;         // unique ID generated by the bot, used for dedup
  channelId: string;
  guildId: string | null;
  content: string;
  triggeredBy: string | null; // optional: which user/action triggered it
  aiEnrich: boolean;          // whether to run AI enrichment before sending
  receivedAt: string;         // ISO timestamp
}

export interface BotReplyQueueEvent {
  kind: "BOT_REPLY";
  interactionId: string;
  token: string;
  applicationId: string;
  content: string;
  retryCount: number;
}

export interface MirrorQueueEvent {
  kind: "MIRROR";
  interactionId: string;
  commandName: string;
  username: string;
  guildId: string | null;
  content: string;
  retryCount: number;
}

export type QueueEventKind = "INTERACTION" | "BOT_MESSAGE" | "BOT_REPLY" | "MIRROR";
export type QueueEvent =
  | InteractionQueueEvent
  | BotMessageQueueEvent
  | BotReplyQueueEvent
  | MirrorQueueEvent;

// ─── Processing State (idempotency) ──────────────────────────────────────────

/**
 * Tracks the processing stage of each event in Redis.
 * Allows crash recovery without re-doing completed steps.
 *
 * State machine:
 *   claimed → discord_done → slack_done → ai_done → db_queued → done
 *
 * For BOT_MESSAGE:
 *   claimed → ai_done → discord_done → db_queued → done
 */
export type ProcessingState =
  | "claimed"       // worker has started; key TTL = 60s (expires if worker crashes)
  | "discord_done"  // Discord reply/send succeeded
  | "slack_done"    // Slack mirror succeeded (INTERACTION only)
  | "ai_done"       // AI step succeeded
  | "db_queued"     // DB write has been added to the batch buffer
  | "done";         // DB flushed, ack'd — key TTL extended to 24h

