// ─── User Session (Redis LRU) ─────────────────────────────────────────────────

/**
 * Per-user, per-channel session stored in Redis with TTL.
 * Provides AI context across multiple questions in the same session.
 *
 * LRU eviction: Redis TTL is refreshed on every interaction.
 * Session expires after SESSION_TTL seconds of inactivity.
 *
 * Key: session:{userId}:{channelId}
 */
export interface UserSession {
  userId: string;
  username: string;
  channelId: string;
  guildId: string | null;
  /** Rolling summary of the conversation so far, updated by AI each turn. */
  recentSummary: string | null;
  /** Last N message contents — sent as context window to the AI. */
  contextMessages: string[];
  /** Total interactions in this session. */
  messageCount: number;
  /** ISO timestamp of last activity. */
  lastActivity: string;
}

